#!/usr/bin/env node
/**
 * gen-vocabulary.mjs — emit the kit's CLASS VOCABULARY for `uicockpit audit`.
 *
 * WHY THIS EXISTS
 * The audit reports `expressible`: of everything it scanned, how much the kit's
 * vocabulary could actually express (there is a recipe · tokens-only · nothing).
 * That needs a reference vocabulary — but the audit runs on codebases that have
 * NO kit yet, so there is no contract to read. The answer is to ship a small
 * slice of the vocabulary inside the CLI package.
 *
 * It must be GENERATED, never hand-written: a hand-maintained list of ~176
 * classes drifts from the recipes within weeks, and this repo's first rule is
 * that component CSS has exactly one source (`src/kit/recipes/index.ts`).
 *
 * Deliberately a SLICE, not the contract: names + modifiers only, no token
 * values (~7 KB vs ~68 KB). The CLI stays cheap to `npx`.
 *
 * Usage:
 *   node scripts/gen-vocabulary.mjs           write ../cli/src/vocabulary.json
 *   node scripts/gen-vocabulary.mjs --check   exit 1 if the file is stale
 *                                             (wired into the build gate)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const RECIPES = join(HERE, '../src/kit/recipes/index.ts')
const OUT = join(HERE, '../../cli/src/vocabulary.json')

/* The SAME selector regex genContract.ts uses — keep them identical, or the
 * audit's idea of "a kit class" drifts from the contract's. */
const SEL = /\.(-?[A-Za-z_][\w-]*)/g

function buildVocabulary(source) {
  const roots = new Map()
  for (const m of source.matchAll(SEL)) {
    const cls = m[1]
    if (!cls) continue
    const dd = cls.indexOf('--')
    const base = dd === -1 ? cls : cls.slice(0, dd)
    const modifier = dd === -1 ? null : cls.slice(dd + 2)
    const uu = base.indexOf('__')
    const root = uu === -1 ? base : base.slice(0, uu)
    if (!root) continue
    let e = roots.get(root)
    if (!e) { e = new Set(); roots.set(root, e) }
    if (modifier) e.add(modifier)
  }
  const classes = {}
  for (const root of [...roots.keys()].sort()) classes[root] = [...roots.get(root)].sort()
  return classes
}

/** Only the recipe CSS matters — the file is a TS module, so a stray selector in
 *  a comment or a doc-card string would otherwise enter the vocabulary. Strip
 *  line comments and block comments first. */
function recipeCss(src) {
  return src.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ')
}

const source = readFileSync(RECIPES, 'utf8')
const classes = buildVocabulary(recipeCss(source))
const roots = Object.keys(classes)

const payload = {
  $comment: 'GENERATED by cockpit/scripts/gen-vocabulary.mjs — do not edit by hand.',
  generator: 'uicockpit',
  // Content hash: the audit stamps this into its output, so two audits taken
  // against different kit versions are never silently compared.
  vocabVersion: createHash('sha256').update(JSON.stringify(classes)).digest('hex').slice(0, 12),
  rootCount: roots.length,
  classes,
}

const next = JSON.stringify(payload, null, 2) + '\n'
const isCheck = process.argv.includes('--check')

if (isCheck) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== next) {
    console.error('✗ cli/src/vocabulary.json is stale — run `npm run gen:vocabulary`')
    process.exit(1)
  }
  console.log(`✓ vocabulary current (${roots.length} roots, ${payload.vocabVersion})`)
} else {
  writeFileSync(OUT, next)
  console.log(`✓ cli/src/vocabulary.json — ${roots.length} roots, version ${payload.vocabVersion}`)
}
